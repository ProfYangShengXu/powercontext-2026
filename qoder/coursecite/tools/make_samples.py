def main() -> None:
    SAMPLES.mkdir(parents=True, exist_ok=True)
    written = 0
    for course, lecture, title, sections in LECTURES:
        folder = SAMPLES / course
        folder.mkdir(parents=True, exist_ok=True)
        lines = [
            "---",
            f"course: {course}",
            f"course_name: {COURSES[course]}",
            f"lecture: {lecture}",
            f"title: {title}",
            "---",
            "",
        ]
        for section, section_title, page, body in sections:
            lines += [f"## {section} {section_title}", f"<!-- page: {page} -->", body, ""]
        path = folder / f"L{lecture:02d}-{title}.md"
        path.write_text("\n".join(lines), encoding="utf-8")
        written += 1
    print(f"wrote {written} lecture files to {SAMPLES}")


if __name__ == "__main__":
    main()
